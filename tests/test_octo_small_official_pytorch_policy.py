def test_horizon_four_ensemble_matches_reference_and_binarizes_after_average():
    from octo_small_official_pytorch.action_ensemble import (
        OfficialTemporalActionEnsembler,
    )
    from simpler_bridge.evaluation import bridge_actions_to_simpler

    ensemble = OfficialTemporalActionEnsembler()
    first = np.zeros((1, 4, 7), dtype=np.float32)
    first[0, 1, 0] = 2.0
    first[0, 1, 6] = 0.49
    second = np.zeros((1, 4, 7), dtype=np.float32)
    second[0, 0, 1] = 4.0
    second[0, 0, 6] = 0.9

    np.testing.assert_array_equal(ensemble.select_action(first), first[0, 0])
    selected = ensemble.select_action(second)

    np.testing.assert_allclose(
        selected,
        [1, 2, 0, 0, 0, 0, 0.695],
        rtol=0,
        atol=1e-7,
    )
    assert bridge_actions_to_simpler(selected, gripper_threshold=0.5)[6] == 1


def test_horizon_four_ensemble_matches_pinned_simpler_reference():
    from octo_small_official_pytorch.action_ensemble import (
        OfficialTemporalActionEnsembler,
    )

    source = (
        Path(__file__).resolve().parents[1]
        / "third_party"
        / "SimplerEnv"
        / "simpler_env"
        / "utils"
        / "action"
        / "action_ensemble.py"
    )
    spec = importlib.util.spec_from_file_location("official_h4_ensemble", source)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    reference = module.ActionEnsembler(pred_action_horizon=4, action_ensemble_temp=0.0)
    implementation = OfficialTemporalActionEnsembler()
    rng = np.random.default_rng(17)

    for _ in range(8):
        actions = rng.normal(size=(1, 4, 7)).astype(np.float32)
        np.testing.assert_allclose(
            implementation.select_action(actions),
            reference.ensemble_action(actions[0]),
            rtol=1e-6,
            atol=1e-6,
        )


def test_remote_policy_ignores_runner_proprio_and_resets_server_episode():
    from octo_small_official_pytorch.ipc import IPC_PROTOCOL_VERSION
    from octo_small_official_pytorch.remote_policy import OctoOfficialRemotePolicy

    class Client:
        def __init__(self):
            self.episodes = []
            self.calls = []

        def metadata(self):
            return {
                "protocol_version": IPC_PROTOCOL_VERSION,
                "protocol_name": "octo-small-official-pytorch-ipc-v1",
                "native_action_chunk_size": 4,
                "action_dim": 7,
                "image_history_horizon": 2,
                "use_proprio": False,
                "device": "cuda:4",
                "checkpoint": {},
                "protocol": {"model_action_gripper": "continuous_model_prediction"},
                "startup_preflight": {"action_shape": [1, 4, 7]},
            }

        def reset_rng(self, seed):
            return seed

        def begin_episode(self, instruction):
            self.episodes.append(instruction)

        def infer(self, image, instruction):
            self.calls.append((image, instruction))
            return np.zeros((1, 4, 7), dtype=np.float32)

    client = Client()
    policy = OctoOfficialRemotePolicy(client)
    image = np.zeros((64, 64, 3), dtype=np.uint8)
    policy.begin_episode("instruction")
    prepared = policy.prepare_observation(image, np.arange(8), "instruction")
    actions = policy.predict_actions(prepared, generator=0)

    assert client.episodes == ["instruction"]
    assert set(prepared) == {"image", "instruction"}
    assert client.calls == [(image, "instruction")]
    assert actions.shape == (1, 4, 7)
    assert policy.model_device == "cuda:4"
    assert policy.protocol_metadata()["gripper_binarization"] == "after_action_ensemble"
