from pathlib import Path

import numpy as np
import pytest


def _statistics_file(tmp_path: Path) -> Path:
    from octo_small_official_pytorch.checkpoint import (
        OFFICIAL_BRIDGE_ACTION_MASK,
        OFFICIAL_BRIDGE_ACTION_MEAN,
        OFFICIAL_BRIDGE_ACTION_STD,
    )

    path = tmp_path / "dataset_statistics.json"
    path.write_text(
        json.dumps(
            {
                "bridge_dataset": {
                    "action": {
                        "mean": list(OFFICIAL_BRIDGE_ACTION_MEAN),
                        "std": list(OFFICIAL_BRIDGE_ACTION_STD),
                        "mask": list(OFFICIAL_BRIDGE_ACTION_MASK),
                    }
                }
            }
        ),
        encoding="utf-8",
    )
    return path


class _Tokenizer:
    def __init__(self):
        self.calls = []

    def __call__(self, instructions, **kwargs):
        self.calls.append((instructions, kwargs))
        return {
            "input_ids": np.arange(16, dtype=np.int64)[None],
            "attention_mask": np.ones((1, 16), dtype=np.int64),
        }


def test_official_statistics_use_mean_std_and_leave_gripper_continuous(tmp_path):
    from octo_small_official_pytorch.checkpoint import (
        OFFICIAL_BRIDGE_ACTION_MEAN,
        OFFICIAL_BRIDGE_ACTION_STD,
    )
    from octo_small_official_pytorch.policy import load_official_action_statistics

    statistics = load_official_action_statistics(_statistics_file(tmp_path))
    normalized = np.ones((1, 4, 7), dtype=np.float32)

    actions = statistics.denormalize_actions(normalized)

    np.testing.assert_allclose(
        actions[0, 0, :6],
        np.asarray(OFFICIAL_BRIDGE_ACTION_MEAN[:6]) + np.asarray(OFFICIAL_BRIDGE_ACTION_STD[:6]),
    )
    assert actions[0, 0, 6] == 1.0
    assert statistics.as_dict()["dataset_name"] == "bridge_dataset"


def test_statistics_loader_rejects_non_released_bridge_values(tmp_path):
    from octo_small_official_pytorch.policy import load_official_action_statistics
    from simpler_bridge.evaluation import SimplerEvaluationError

    path = _statistics_file(tmp_path)
    document = json.loads(path.read_text(encoding="utf-8"))
    document["bridge_dataset"]["action"]["mean"][0] = 0.0
    path.write_text(json.dumps(document), encoding="utf-8")

    with pytest.raises(SimplerEvaluationError, match="released Octo-small"):
        load_official_action_statistics(path)


def test_tensorflow_lanczos3_resize_matches_pinned_simpler_reference():
    from octo_small_official_pytorch.policy import resize_image_tensorflow_lanczos3

    y, x = np.indices((480, 640), dtype=np.int64)
    image = np.stack(
        (
            (3 * y + 5 * x) % 256,
            (11 * y + 7 * x + 13) % 256,
            (17 * y + 19 * x + 29) % 256,
        ),
        axis=-1,
    ).astype(np.uint8)

    resized = resize_image_tensorflow_lanczos3(image, size=(256, 256))

    # Generated by pinned SimplerEnv's tf.image.resize(lanczos3, antialias=True),
    # followed by round/clip/uint8, for the deterministic 480x640 input above.
    assert hashlib.sha256(resized.tobytes()).hexdigest() == (
        "7185cc4c8360d6c9d80aaf180c298e5d327a71b8c3379f8ef69608a387c4abd6"
    )


