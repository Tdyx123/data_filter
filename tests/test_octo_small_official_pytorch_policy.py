def test_episode_history_grows_to_two_frames_and_reset_prevents_leakage(tmp_path):
    from octo_small_official_pytorch.policy import (
        OctoOfficialModelPolicy,
        load_official_action_statistics,
    )

    tokenizer = _Tokenizer()
    policy = OctoOfficialModelPolicy(
        model=object(),
        tokenizer=tokenizer,
        statistics=load_official_action_statistics(_statistics_file(tmp_path)),
        device="cpu",
        precision="fp32",
        sampler=lambda prepared, generator: np.zeros((1, 4, 7), dtype=np.float32),
        generator_factory=lambda device, seed: (device, seed),
    )
    first = np.zeros((12, 20, 3), dtype=np.uint8)
    second = np.full((12, 20, 3), 255, dtype=np.uint8)

    policy.begin_episode("Pick up the object")
    prepared_one = policy.prepare_observation(first, "Pick up the object")
    prepared_two = policy.prepare_observation(second, "Pick up the object")

    assert set(prepared_one) == {
        "image_primary",
        "timestep_pad_mask",
        "language_input_ids",
        "language_attention_mask",
    }
    assert prepared_one["image_primary"].shape == (1, 1, 3, 256, 256)
    assert prepared_two["image_primary"].shape == (1, 2, 3, 256, 256)
    assert "proprio" not in prepared_two
    assert tokenizer.calls[0][0] == ["Pick up the object"]
    assert len(tokenizer.calls) == 1

    policy.begin_episode("Place the object")
    prepared_reset = policy.prepare_observation(second, "Place the object")

    assert prepared_reset["image_primary"].shape == (1, 1, 3, 256, 256)
    assert len(tokenizer.calls) == 2
    assert policy.make_generator(7) == ("cpu", 7)


def test_policy_output_is_strictly_horizon_four_and_batch_never_has_proprio(tmp_path):
    from octo_small_official_pytorch.policy import (
        OctoOfficialModelPolicy,
        load_official_action_statistics,
    )

    observed = []

    def sample(prepared, generator):
        observed.append((prepared, generator))
        result = np.zeros((1, 4, 7), dtype=np.float32)
        result[..., 6] = 0.75
        return result

    policy = OctoOfficialModelPolicy(
        model=object(),
        tokenizer=_Tokenizer(),
        statistics=load_official_action_statistics(_statistics_file(tmp_path)),
        device="cpu",
        precision="fp32",
        sampler=sample,
    )
    policy.begin_episode("instruction")
    prepared = policy.prepare_observation(np.zeros((32, 32, 3), dtype=np.uint8), "instruction")
    actions = policy.predict_actions(prepared, generator="rng")

    assert actions.shape == (1, 4, 7)
    assert "proprio" not in observed[0][0]
    assert actions[0, 0, 6] == 0.75
    assert policy.protocol_metadata()["use_proprio"] is False
    assert policy.protocol_metadata()["image_history_horizon"] == 2


